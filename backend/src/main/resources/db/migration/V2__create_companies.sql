-- V2: companies become records. Each QR code now belongs to a company by id.

CREATE TABLE companies (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(128) NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_companies_name UNIQUE (name)
);

-- Keep existing codes working: one company per distinct company_id already in use.
INSERT INTO companies (name)
SELECT DISTINCT company_id FROM qr_codes;

-- Swap the old text column for a proper reference.
ALTER TABLE qr_codes ADD COLUMN company_ref BIGINT;

UPDATE qr_codes q
SET company_ref = c.id
FROM companies c
WHERE c.name = q.company_id;

ALTER TABLE qr_codes ALTER COLUMN company_ref SET NOT NULL;
ALTER TABLE qr_codes DROP COLUMN company_id;   -- also drops idx_qr_codes_company
ALTER TABLE qr_codes RENAME COLUMN company_ref TO company_id;

ALTER TABLE qr_codes
    ADD CONSTRAINT fk_qr_codes_company FOREIGN KEY (company_id) REFERENCES companies (id);

CREATE INDEX idx_qr_codes_company ON qr_codes (company_id);